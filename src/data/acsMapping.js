// ── Helper: get pages linked to an ACS code ────────────────────────────────
export const getACSPages = (code, phakData) => {
  const pageIds = acsMapping[code] || [];
  if (!phakData || pageIds.length === 0) return [];

  const results = [];
  phakData.chapters.forEach(chapter => {
    chapter.pages.forEach(page => {
      if (pageIds.includes(page.page_number)) {
        results.push({
          page_number: page.page_number,
          page_title: page.page_title,
          chapter_number: chapter.chapter_number,
          chapter_title: chapter.title,
        });
      }
    });
  });
  results.sort((a, b) => {
    const [ac, ap] = a.page_number.split('-').map(Number);
    const [bc, bp] = b.page_number.split('-').map(Number);
    return ac !== bc ? ac - bc : ap - bp;
  });
  return results;
};

// ── Helper: get ACS codes for a given page ─────────────────────────────────
export const getPageACSCodes = (pageId) => {
  return Object.entries(acsMapping)
    .filter(([, pages]) => pages.includes(pageId))
    .map(([code]) => code);
};
